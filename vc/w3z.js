const { chromium } = require('playwright');
const fs = require('fs');
const dir = require('path').resolve(__dirname, '..') + '/';
const three = fs.readFileSync(dir + 'vc/three/package/build/three.min.js', 'utf8');
const src = fs.readFileSync(dir + 'voice-crew.html', 'utf8');
fs.writeFileSync(dir + 'vc/test-page.html', '<!doctype html><html><head><meta charset="utf8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0}[hidden]{display:none!important}</style></head><body>' + src.replace(/<!doctype html>[\s\S]*?<body>/i, '').replace(/<\/body>\s*<\/html>\s*$/i, '') + '</body></html>');
const w3w = fs.readFileSync(dir + 'vc/w3w.js', 'utf8');
const m = /const stub = \(voice\) => `([\s\S]*?)`;\nconst bulk/.exec(w3w);
const stub = (voice) => eval('`' + m[1] + '`');
(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--use-gl=angle'] });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
  const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.route('**/three.min.js', r => r.fulfill({ contentType: 'application/javascript', body: three }));
  await page.addInitScript(stub('true'));
  await page.clock.install();
  await page.addInitScript(() => { window.requestAnimationFrame = function () { return 0; }; });
  await page.goto('file://' + dir + 'vc/test-page.html'); await page.clock.runFor(1500);
  const st = () => page.evaluate(() => ({ call: !document.getElementById('callbar').hidden, sys: [...document.querySelectorAll('#log .sysmsg')].map(x => x.textContent), last: [...document.querySelectorAll('#log .row')].slice(-1).map(r => r.querySelector('b').textContent + ': ' + r.querySelector('.say').textContent), spoken: window.__spoken.slice(-2) }));
  await page.click('#listenBtn'); await page.clock.runFor(500);
  await page.evaluate(() => window.__say('Hey Mia')); await page.clock.runFor(4000);
  console.log('0 call open (Listen on)', JSON.stringify(await st()));
  await page.clock.fastForward(155000); await page.clock.runFor(2500);
  console.log('1 after 2.5 quiet minutes: still there?', JSON.stringify(await st()));
  await page.evaluate(() => window.__say('yes I am here')); await page.clock.runFor(4000);
  console.log('2 spoke again, call stays', JSON.stringify(await st()));
  await page.clock.fastForward(155000); await page.clock.runFor(2500);
  await page.clock.fastForward(65000); await page.clock.runFor(2500);
  const fin = await st();
  console.log('3 ended with a goodbye and a visible note', JSON.stringify(fin));
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
